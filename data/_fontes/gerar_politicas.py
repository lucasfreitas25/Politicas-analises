def categoria_status(status):
    """Padroniza o texto livre de 'status' em cinco faixas comparáveis."""
    s = status.lower()
    if any(k in s for k in ("revogad", "substitu", "encerrad", "revertido em", "declarado inconstitucional",
                            "limite derrubado", "veto derrubado")):
        return "Deixou de valer"
    if "parcialmente" in s or "revertido parcialmente" in s:
        return "Em vigor em parte"
    if any(k in s for k in ("aguardando", "disputa", "investiga")):
        return "Em tramitação ou disputa"
    if any(k in s for k in ("conclu", "julgado")):
        return "Concluída"
    return "Em vigor"


